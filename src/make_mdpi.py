"""Write paper/main_mdpi.tex: the paper in MDPI's official article template (submission version).

Everything is generated from paper/main.tex, paper/appendix.tex and paper/tables/, so the IEEE and MDPI versions
never diverge. Only the front matter (a 200-word abstract, as MDPI asks) and MDPI's required back-matter
statements are written here. The template's class files are in paper/Definitions/ (MDPI LaTeX template, as
downloaded from MDPI). Build: cd paper && tectonic -X compile main_mdpi.tex
"""
