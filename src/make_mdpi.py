def between(s, a, b):
    i = s.index(a) + len(a)
    return s[i:s.index(b, i)]


def brace_arg(s, cmd):
    i = s.index(cmd) + len(cmd)
    assert s[i] == "{"
    depth = 0
    for k in range(i, len(s)):
        depth += {"{": 1, "}": -1}.get(s[k], 0)
        if depth == 0:
            return s[i + 1:k]


def to_mdpi(s):
    """IEEE body -> MDPI body: inline tables, MDPI theorem names, full-width floats, T1-safe characters."""
    s = re.sub(r"\\input\{(tables/[^}]+)\}", lambda m: (P / f"{m.group(1).removesuffix('.tex')}.tex").read_text(), s)
    for env in ("proposition", "lemma", "corollary", "theorem"):
        s = s.replace(rf"\begin{{{env}}}", rf"\begin{{{env.capitalize()}}}").replace(rf"\end{{{env}}}", rf"\end{{{env.capitalize()}}}")
    s = s.replace(r"\begin{IEEEproof}", r"\begin{proof}").replace(r"\end{IEEEproof}", r"\end{proof}")
    # Wide floats use the full page width, as in MDPI's template
    s = re.sub(r"\\begin\{(table|figure)\*\}(\[[^]]*\])?", r"\\begin{\1}[t]\n\\begin{adjustwidth}{-\\extralength}{0cm}", s)
    s = re.sub(r"\\end\{(table|figure)\*\}", r"\\end{adjustwidth}\n\\end{\1}", s)
    s = s.replace(r"width=\textwidth", r"width=\linewidth").replace(r"\begin{tabularx}{\textwidth}", r"\begin{tabularx}{\linewidth}")
    s = s.replace("ś", r"\'{s}").replace("Ö", r"\"{O}")
    assert "IEEE" not in s, re.findall(r".{40}IEEE.{40}", s)[:3]
    return s


